def filter_span_for_alpha(alpha: float) -> int:
    """Span del SRRC (en símbolos) adecuado para el roll-off dado."""
    for alpha_min, span in FILTER_SPAN_BY_ALPHA:
        if alpha >= alpha_min:
            return span
    return FILTER_SPAN_BY_ALPHA[-1][1]
